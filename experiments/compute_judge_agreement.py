"""Compute per-benchmark human-vs-judge agreement, Cohen's kappa, and a 95% bootstrap CI.

Joins user-labeled CSVs (downloaded from Google Sheets) against the original
stratified sample generated by ``sample_for_judge_validation.py``.

When the extra annotator files listed in ``ANNOTATOR_FILES`` are present, the
report also covers inter-annotator agreement: Fleiss' kappa across all raters,
pairwise Cohen's kappa, and judge-vs-majority agreement. Those files are
optional; without them the script behaves exactly as before.

Layout of ``analysis/judge_validation/`` (inputs first, generated last):

* ``human_labels.csv``          stratified sample carrying the judge's verdicts.
* ``{benchmark}_labeled.csv``   annotator 1's labels, one file per benchmark.
* ``annotator_blind.csv``       blind template handed to annotators 2 and 3;
                                the judge verdict and annotator 1's label are
                                withheld so their labels stay independent.
* ``annotator_{n}_labels.csv``  a returned copy of that template, one per extra
                                annotator, with ``your_label`` filled in.
* ``merged_labels.csv``         GENERATED: sample + judge verdict + annotator 1.
* ``judge_agreement_report.md`` GENERATED: the report this script prints.
"""

from __future__ import annotations

import csv
import itertools
import random
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

CODE_ROOT = Path(__file__).resolve().parents[1]
ORIGINAL_CSV = CODE_ROOT / "analysis" / "judge_validation" / "human_labels.csv"
USER_FILES = {
    "bcp": CODE_ROOT / "analysis" / "judge_validation" / "bcp_labeled.csv",
    "qasper": CODE_ROOT / "analysis" / "judge_validation" / "qasper_labeled.csv",
    "financebench": CODE_ROOT / "analysis" / "judge_validation" / "financebench_labeled.csv",
    "qasper_rag": CODE_ROOT / "analysis" / "judge_validation" / "qasper_rag_labeled.csv",
}

OUT_DIR = CODE_ROOT / "analysis" / "judge_validation"
OUT_MERGED = OUT_DIR / "merged_labels.csv"
OUT_REPORT = OUT_DIR / "judge_agreement_report.md"
N_BOOTSTRAP = 10_000
SEED = 20260424

# Extra annotators who labeled the blind template independently. Annotator 1 is
# the per-benchmark ``USER_FILES`` above, whose labels land in ``merged_labels.csv``
# as ``human_label``. Missing files are skipped, so the multi-annotator section of
# the report simply does not appear until the labels are collected.
ANNOTATOR_FILES = {
    "annotator_2": OUT_DIR / "annotator_2_labels.csv",
    "annotator_3": OUT_DIR / "annotator_3_labels.csv",
}
BLIND_LABEL_COLUMN = "your_label (yes/no)"

# Column names vary across the label files: the annotators' originals carried
# parenthesised glosses in their own language, and the released copies carry
# plain English. Matching on the prefix reads either without hard-coding the
# glosses, which would put the authors' language into a released script.
_COLUMN_ALIASES = {
    "predicted_answer": ("predicted_answer",),
    "gold_answer": ("gold_answer",),
    "your_label": ("your_label",),
    "justification": ("justification",),
}


def col(row: dict, name: str):
    """Return row[name] under whichever header variant the file uses.

    Falls back to a prefix match so a header carrying a parenthesised gloss
    ("gold_answer (...)") resolves without the gloss being written down here.
    """
    for candidate in _COLUMN_ALIASES.get(name, (name,)):
        if candidate in row:
            return row[candidate]
    for key in row:
        stripped = key.lstrip("\ufeff").strip()
        if stripped == name or stripped.startswith(name + " (") or stripped.startswith(name + "("):
            return row[key]
    raise KeyError(f"{name}: no column matching it in {list(row)[:8]}")


VALID_LABELS = frozenset({"yes", "no"})


@dataclass
class Row:
    benchmark: str
    query_id: str
    phase: str
    question: str
    gold_answer: str
    predicted_answer: str
    judge_verdict: str
    human_label: str


def load_original() -> list[dict]:
    with open(ORIGINAL_CSV) as f:
        return list(csv.DictReader(f))


def strip_bench_prefix(qid: str, benchmark: str) -> str:
    """Users may have stripped the 'financebench_' prefix; normalise."""
    prefix = f"{benchmark}_"
    if qid.startswith(prefix):
        return qid[len(prefix) :]
    return qid


def load_user(path: Path, benchmark: str) -> list[dict]:
    with open(path) as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        r["benchmark"] = benchmark
        # Normalise query_id: some benchmarks were labeled with or without the
        # benchmark prefix.
        r["query_id_norm"] = strip_bench_prefix(r["query_id"], benchmark)
        r["your_label"] = col(r, "your_label").strip().lower()
    return rows


def load_annotator_labels(path: Path) -> dict[tuple[str, str, str], str]:
    """Load one returned blind template, keyed by (benchmark, query_id, phase).

    Annotators return the template from a spreadsheet tool that writes a BOM, so
    it is read as utf-8-sig. Blank labels are dropped rather than coerced: a row
    an annotator skipped must not be counted as agreement with anyone. A label
    outside ``VALID_LABELS`` is reported and dropped too, because the kappa
    routines only recognise those categories and would otherwise fold an
    unreadable cell into the score without saying so.
    """
    with open(path, encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))
    labels: dict[tuple[str, str, str], str] = {}
    for r in rows:
        try:
            label = (col(r, "your_label") or "").strip().lower()
        except KeyError:
            label = (r.get(BLIND_LABEL_COLUMN) or "").strip().lower()
        if not label:
            continue
        if label not in VALID_LABELS:
            print(
                f"[WARN] {path.name}: dropping unrecognised label {label!r} on "
                f"{r['benchmark']}/{r['query_id']}/{r['phase']}; expected one of "
                f"{sorted(VALID_LABELS)}"
            )
            continue
        labels[(r["benchmark"], r["query_id"], r["phase"])] = label
    return labels


def _prefix_key(s: str, n: int = 30) -> str:
    """Google Sheets truncates long cells; use first n alphanumerics as a fuzzy key."""
    s = s.strip().lower()
    # Drop anything after the first "..." or ellipsis character.
    for sep in ("...", "…"):
        if sep in s:
            s = s.split(sep)[0]
    return "".join(ch for ch in s if ch.isalnum())[:n]


def merge(original: list[dict], user: list[dict], benchmark: str) -> list[Row]:
    orig_b = [r for r in original if r["benchmark"] == benchmark]

    # Group originals by normalised query_id; within a qid we disambiguate by
    # prefix-matching the (possibly truncated) predicted_answer from the user CSV.
    from collections import defaultdict

    by_qid: dict[str, list[dict]] = defaultdict(list)
    for r in orig_b:
        qid_norm = strip_bench_prefix(r["query_id"], benchmark)
        by_qid[qid_norm].append(r)

    merged = []
    used_keys: set[tuple[str, str]] = set()
    unmatched = []
    for u in user:
        qid = u["query_id_norm"].strip()
        user_pred = col(u, "predicted_answer")
        candidates = by_qid.get(qid, [])
        if not candidates:
            unmatched.append(u)
            continue

        # Prefer the candidate whose predicted-answer prefix best matches the
        # user's (possibly truncated) predicted answer.
        u_key = _prefix_key(user_pred)
        scored = []
        for c in candidates:
            c_key = _prefix_key(c["predicted_answer"])
            # Score is length of common prefix.
            common = 0
            for a, b in zip(u_key, c_key):
                if a == b:
                    common += 1
                else:
                    break
            scored.append((common, c))
        scored.sort(key=lambda x: -x[0])
        # Pick the best match whose (qid, phase) hasn't been used yet.
        src = None
        for _, c in scored:
            key = (c["query_id"], c["phase"])
            if key not in used_keys:
                src = c
                used_keys.add(key)
                break
        if src is None:
            src = scored[0][1] if scored else None
        if src is None:
            unmatched.append(u)
            continue

        merged.append(
            Row(
                benchmark=benchmark,
                query_id=src["query_id"],
                phase=src["phase"],
                question=src["question"],
                gold_answer=src["gold_answer"],
                predicted_answer=src["predicted_answer"],
                judge_verdict=src["judge_verdict"].strip().lower(),
                human_label=col(u, "your_label").strip().lower(),
            )
        )

    if unmatched:
        print(f"[WARN] {benchmark}: {len(unmatched)} user rows did not match original. First:")
        for u in unmatched[:3]:
            print(f"   qid_norm={u['query_id_norm']!r} pred={col(u, 'predicted_answer')[:60]!r}")
    return merged


def kappa_score(y1: list[str], y2: list[str]) -> float:
    """Cohen's kappa for two binary raters (labels in {'yes','no'})."""
    n = len(y1)
    if n == 0:
        return float("nan")
    # Observed agreement
    po = sum(1 for a, b in zip(y1, y2) if a == b) / n
    # Expected agreement by chance
    p1_y = sum(1 for x in y1 if x == "yes") / n
    p2_y = sum(1 for x in y2 if x == "yes") / n
    pe = p1_y * p2_y + (1 - p1_y) * (1 - p2_y)
    if pe == 1:
        return float("nan")
    return (po - pe) / (1 - pe)


def fleiss_kappa(ratings: list[list[str]]) -> float:
    """Fleiss' kappa over items rated by the same fixed number of raters.

    ``ratings`` carries one list of labels per item; each item must hold the same
    number of labels, drawn from {'yes','no'}. Cohen's kappa above covers the
    two-rater case; this generalises it to three or more.
    """
    n_items = len(ratings)
    if n_items == 0:
        return float("nan")
    n_raters = len(ratings[0])
    if n_raters < 2:
        return float("nan")

    categories = ("yes", "no")
    per_item_agreement = []
    category_totals = {c: 0 for c in categories}
    for item in ratings:
        counts = {c: item.count(c) for c in categories}
        for c in categories:
            category_totals[c] += counts[c]
        agreeing_pairs = sum(counts[c] * (counts[c] - 1) for c in categories)
        per_item_agreement.append(agreeing_pairs / (n_raters * (n_raters - 1)))

    p_bar = sum(per_item_agreement) / n_items
    p_e = sum((category_totals[c] / (n_items * n_raters)) ** 2 for c in categories)
    if p_e == 1:
        return float("nan")
    return (p_bar - p_e) / (1 - p_e)


def bootstrap_ci(y1: list[str], y2: list[str], n_samples: int, seed: int) -> tuple[float, float]:
    rng = random.Random(seed)
    n = len(y1)
    stats = []
    for _ in range(n_samples):
        idx = [rng.randrange(n) for _ in range(n)]
        stats.append(kappa_score([y1[i] for i in idx], [y2[i] for i in idx]))
    stats.sort()
    lo = stats[int(0.025 * n_samples)]
    hi = stats[int(0.975 * n_samples)]
    return lo, hi


def confusion(y_true: list[str], y_pred: list[str]) -> dict:
    """y_true = human, y_pred = judge."""
    tp = sum(1 for a, b in zip(y_true, y_pred) if a == "yes" and b == "yes")
    fn = sum(1 for a, b in zip(y_true, y_pred) if a == "yes" and b == "no")
    fp = sum(1 for a, b in zip(y_true, y_pred) if a == "no" and b == "yes")
    tn = sum(1 for a, b in zip(y_true, y_pred) if a == "no" and b == "no")
    return {"tp": tp, "fn": fn, "fp": fp, "tn": tn}


def iaa_block(rows: list[Row]) -> list[str]:
    """Report inter-annotator agreement; empty when no extra annotator has labeled."""
    available = {name: p for name, p in ANNOTATOR_FILES.items() if p.exists()}
    for name, path in ANNOTATOR_FILES.items():
        if name not in available:
            print(f"[WARN] no labels for {name} at {path}; excluded from the IAA section")
    if not available:
        return []

    extra = {name: load_annotator_labels(path) for name, path in available.items()}
    rater_names = ["annotator_1", *extra]

    judge: list[str] = []
    ratings: list[list[str]] = []
    incomplete = 0
    for r in rows:
        key = (r.benchmark, r.query_id, r.phase)
        labels = [r.human_label] + [extra[name].get(key, "") for name in extra]
        if r.judge_verdict and all(labels):
            judge.append(r.judge_verdict)
            ratings.append(labels)
        else:
            incomplete += 1
    if not ratings:
        print("[ERR] no row carries a label from every annotator; skipping the IAA section")
        return []

    n = len(ratings)
    by_rater = {name: [item[i] for item in ratings] for i, name in enumerate(rater_names)}
    majority = [Counter(item).most_common(1)[0][0] for item in ratings]
    unanimous = sum(1 for item in ratings if len(set(item)) == 1)
    judge_majority = sum(1 for j, m in zip(judge, majority) if j == m)

    block = [
        f"## Inter-annotator agreement (n={n})\n",
        f"Raters: {', '.join(rater_names)}. Every annotator after the first labeled a "
        "blind copy of the sample, with the judge's verdict and the other annotators' "
        "labels withheld, so their judgements are independent.\n",
    ]
    if incomplete:
        block.append(
            f"Rows lacking a label from at least one rater, excluded here: {incomplete}.\n"
        )
    block += [
        f"- Fleiss' kappa across {len(rater_names)} human raters: {fleiss_kappa(ratings):.3f}",
        f"- Unanimous rows: {unanimous}/{n} ({unanimous / n * 100:.1f}%)",
        f"- Judge matches the human majority: {judge_majority}/{n} ({judge_majority / n * 100:.1f}%)",
        "- Pairwise percent agreement and Cohen's kappa:",
    ]
    series = {"judge": judge, **by_rater}
    for a, b in itertools.combinations(series, 2):
        ya, yb = series[a], series[b]
        agree = sum(1 for x, y in zip(ya, yb) if x == y)
        block.append(
            f"    {a} vs {b}: {agree / n * 100:.1f}% ({agree}/{n}), kappa={kappa_score(ya, yb):.3f}"
        )
    block.append("")
    return block


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    original = load_original()

    all_merged: list[Row] = []
    per_bench: dict[str, list[Row]] = {}
    for benchmark, fp in USER_FILES.items():
        if not fp.exists():
            print(f"[ERR] missing user file for {benchmark}: {fp}")
            continue
        user = load_user(fp, benchmark)
        merged = merge(original, user, benchmark)
        per_bench[benchmark] = merged
        all_merged.extend(merged)
        print(
            f"{benchmark}: merged {len(merged)} / user {len(user)} rows; "
            f"judge={sum(1 for r in merged if r.judge_verdict == 'yes')} yes / "
            f"human={sum(1 for r in merged if r.human_label == 'yes')} yes"
        )

    # Write merged CSV
    with open(OUT_MERGED, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, quoting=csv.QUOTE_ALL)
        w.writerow(
            [
                "benchmark",
                "query_id",
                "phase",
                "question",
                "gold_answer",
                "predicted_answer",
                "judge_verdict",
                "human_label",
            ]
        )
        for r in all_merged:
            w.writerow(
                [
                    r.benchmark,
                    r.query_id,
                    r.phase,
                    r.question,
                    r.gold_answer,
                    r.predicted_answer,
                    r.judge_verdict,
                    r.human_label,
                ]
            )

    # Per-benchmark + overall analysis
    lines = [
        "# LLM judge validation against human labels\n",
        f"Sampling: stratified 25 judge=yes / 25 judge=no per benchmark, seed {SEED}.\n",
        f"Bootstrap: {N_BOOTSTRAP} resamples for 95% CI on Cohen's kappa.\n",
    ]

    def row_block(name: str, rows: list[Row]) -> list[str]:
        j = [r.judge_verdict for r in rows]
        h = [r.human_label for r in rows]
        agree = sum(1 for a, b in zip(j, h) if a == b) / max(1, len(rows))
        k = kappa_score(h, j)
        ci = bootstrap_ci(h, j, N_BOOTSTRAP, SEED)
        conf = confusion(h, j)
        p = conf["tp"] / max(1, conf["tp"] + conf["fp"])
        r = conf["tp"] / max(1, conf["tp"] + conf["fn"])
        f1 = 2 * p * r / max(1e-9, p + r)
        block = [
            f"## {name} (n={len(rows)})\n",
            f"- Percent agreement: {agree * 100:.1f}%",
            f"- Cohen's kappa: {k:.3f} (95% bootstrap CI [{ci[0]:.3f}, {ci[1]:.3f}])",
            f"- Confusion matrix (rows=human, cols=judge):",
            f"    human=yes, judge=yes: {conf['tp']} (TP)",
            f"    human=yes, judge=no : {conf['fn']} (FN — judge missed a correct answer)",
            f"    human=no,  judge=yes: {conf['fp']} (FP — judge accepted an incorrect answer)",
            f"    human=no,  judge=no : {conf['tn']} (TN)",
            f"- Judge precision: {p:.3f}, recall: {r:.3f}, F1: {f1:.3f}",
            "",
        ]
        return block

    for benchmark, rows in per_bench.items():
        lines.extend(row_block(benchmark, rows))
    lines.extend(row_block("overall", all_merged))
    lines.extend(iaa_block(all_merged))

    # Write report
    OUT_REPORT.write_text("\n".join(lines))
    print(f"\nWrote merged CSV to {OUT_MERGED}")
    print(f"Wrote report to {OUT_REPORT}")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
